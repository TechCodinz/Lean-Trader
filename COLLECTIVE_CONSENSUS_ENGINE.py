_global_consensus_engine = None

def initialize_collective_consensus(all_engines: Dict[str, Any]) -> CollectiveConsensusEngine:
    """
    Initialize the global collective consensus engine
    
    Args:
        all_engines: Dict of ALL engine instances
    
    Returns:
        CollectiveConsensusEngine instance
    """
    global _global_consensus_engine
    _global_consensus_engine = CollectiveConsensusEngine(all_engines)
    return _global_consensus_engine


def get_collective_consensus() -> Optional[CollectiveConsensusEngine]:
    """
    Get the global collective consensus engine
    
    Returns:
        CollectiveConsensusEngine instance or None if not initialized
    """
    return _global_consensus_engine


