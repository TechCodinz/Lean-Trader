        # $0-$20: Very aggressive (60% agreement, 60% confidence)
        # $20-$100: Aggressive (65% agreement, 65% confidence)
        # $100-$500: Balanced (70% agreement, 70% confidence)
        # $500+: Selective (75% agreement, 75% confidence)
